INSERT INTO public.product_variants (
  variant_id, product_id, position, sku, barcode, option1_name, option1_value,
  option2_name, option2_value, option3_name, option3_value, image_url, weight,
  weight_unit, price, compare_at_price, taxable, inventory_item_id,
  inventory_tracker, inventory_policy, fulfillment_service, requires_shipping,
  shipping_profile, inventory_qty, cost, hs_code, country_of_origin, province_of_origin
