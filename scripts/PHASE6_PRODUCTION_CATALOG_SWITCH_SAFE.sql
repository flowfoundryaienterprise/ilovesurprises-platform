-- 2B. Parent-to-Child Insertion with 100% Named Columns
INSERT INTO public.collections (
  collection_id, handle, title, body_html, sort_order, template_suffix,
  updated_at, image_url, products_count, published_online_store, source_type,
  inclusion_type, inclusion_match, seo_title, seo_description,
  smartseo_meta_title, smartseo_meta_description, smartseo_meta_keywords
