  id, product_id, image_url, image_type, position, width, height, alt_text
FROM public.staging_product_images;

INSERT INTO public.product_options (
  option_key, product_id, position, source_name
)
SELECT 
  option_key, product_id, position, source_name
FROM public.staging_product_options;

INSERT INTO public.product_option_values (
  id, option_key, product_id, value
)
SELECT 
  id, option_key, product_id, value
FROM public.staging_product_option_values;

INSERT INTO public.product_collections (
  collection_id, product_id, collection_handle, product_handle,
  sort_position, source_verified
)
SELECT 
  collection_id, product_id, collection_handle, product_handle,
  sort_position, source_verified
FROM public.staging_product_collections;

INSERT INTO public.collection_conditions (
  id, collection_id, condition_no, field, relation, value, match
)
SELECT 
  id, collection_id, condition_no, field, relation, value, match
FROM public.staging_collection_conditions;

INSERT INTO public.collection_metafields (
  id, collection_id, namespace_key, metafield_type, value
