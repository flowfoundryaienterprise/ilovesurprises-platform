-- STEP 1: Ensure Production Tables Exist (bigint-safe for inventory)
CREATE TABLE IF NOT EXISTS public.products (
  product_id text PRIMARY KEY,
  handle text UNIQUE NOT NULL,
  title text NOT NULL,
  body_html text,
  vendor text,
  product_type text,
  tags text,
  created_at timestamptz,
  updated_at timestamptz,
  status text,
  published boolean,
  published_at timestamptz,
  template_suffix text,
  gift_card boolean,
  source_url text,
  total_inventory_qty bigint,
  category_id text,
  category_name text,
  seo_title text,
  seo_description text
);

CREATE TABLE IF NOT EXISTS public.product_variants (
  variant_id text PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(product_id),
  position integer,
  sku text,
  barcode text,
  option1_name text,
  option1_value text,
  option2_name text,
  option2_value text,
  option3_name text,
  option3_value text,
  image_url text,
  weight numeric,
  weight_unit text,
  price numeric,
  compare_at_price numeric,
  taxable boolean,
  inventory_item_id text,
  inventory_tracker text,
  inventory_policy text,
  fulfillment_service text,
  requires_shipping boolean,
  shipping_profile text,
  inventory_qty integer,
  cost numeric,
  hs_code text,
  country_of_origin text,
  province_of_origin text
);

CREATE TABLE IF NOT EXISTS public.product_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(product_id),
  image_url text NOT NULL,
  image_type text,
  position integer,
  width integer,
  height integer,
  alt_text text
);

CREATE TABLE IF NOT EXISTS public.product_options (
  option_key text PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(product_id),
  position integer NOT NULL,
  source_name text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.product_option_values (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  option_key text NOT NULL REFERENCES public.product_options(option_key),
  product_id text NOT NULL REFERENCES public.products(product_id),
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.collections (
  collection_id text PRIMARY KEY,
  handle text UNIQUE NOT NULL,
  title text NOT NULL,
  body_html text,
  sort_order text,
  template_suffix text,
  updated_at timestamptz,
  image_url text,
  products_count integer,
  published_online_store boolean,
  source_type text,
  inclusion_type text,
  inclusion_match text,
  seo_title text,
  seo_description text,
  smartseo_meta_title text,
  smartseo_meta_description text,
  smartseo_meta_keywords text
);

CREATE TABLE IF NOT EXISTS public.product_collections (
  collection_id text NOT NULL REFERENCES public.collections(collection_id),
  product_id text NOT NULL REFERENCES public.products(product_id),
  collection_handle text,
  product_handle text,
  sort_position integer,
  source_verified text,
  PRIMARY KEY (collection_id, product_id)
);

CREATE TABLE IF NOT EXISTS public.collection_conditions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collection_id text NOT NULL REFERENCES public.collections(collection_id),
  condition_no integer,
  field text,
  relation text,
  value text,
  match text
);

CREATE TABLE IF NOT EXISTS public.collection_metafields (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collection_id text NOT NULL REFERENCES public.collections(collection_id),
  namespace_key text NOT NULL,
  metafield_type text,
  value text
);

CREATE TABLE IF NOT EXISTS public.product_metafields (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(product_id),
  namespace_key text NOT NULL,
  metafield_type text,
  value text
);

CREATE TABLE IF NOT EXISTS public.variant_metafields (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  variant_id text NOT NULL REFERENCES public.product_variants(variant_id),
  namespace_key text NOT NULL,
  metafield_type text,
  value text
);

-- Ensure column type is bigint if previously created as integer
ALTER TABLE public.products ALTER COLUMN total_inventory_qty TYPE bigint;

-- STEP 2: Atomic Transaction for Safe Data Replacement (NO CASCADE)
BEGIN;

-- 2A. Explicit Child-to-Parent Deletion (Guarantees zero impact on non-catalog tables)
DELETE FROM public.collection_metafields;
DELETE FROM public.collection_conditions;
DELETE FROM public.product_collections;
